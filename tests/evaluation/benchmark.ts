/**
 * NL2SQL benchmark. Each answerable case carries:
 *   - expectedTables : the tables a correct query needs at minimum (routing recall is measured against this)
 *   - expectedMetrics: registry metrics that should be recognised (optional)
 *   - expectedConcepts: business concepts the question is about (documentation + analyzer checks)
 *   - referenceSql   : hand-written gold query; its result is the expected result
 *   - compare        : "result" → generated result must equal the gold result (execution accuracy);
 *                      "shape"  → only row-count / column-count characteristics are compared
 * Reference SQL is validated and executed against the real database by tests/integration/benchmark-gold.test.ts.
 */

export interface BenchmarkCase {
  id: string;
  question: string;
  category: "ranking" | "aggregation" | "trend" | "count" | "comparison" | "lookup" | "ratio";
  expectedTables: string[];
  expectedMetrics?: string[];
  expectedConcepts: string[];
  referenceSql: string;
  compare: "result" | "shape";
  /** Expected result characteristics (checked against the gold result and, in the LLM eval, the generated result). */
  shape: { minRows: number; maxRows?: number; minColumns: number };
}

export interface NegativeCase {
  id: string;
  question: string;
  kind: "out_of_scope" | "ambiguous" | "write_request";
}

